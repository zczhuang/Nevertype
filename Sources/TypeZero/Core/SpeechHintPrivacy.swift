import AppKit
import Foundation

/// What a dictation may take from the clipboard as a speech hint.
///
/// A speech hint is a word the recognizer is told to expect. A cloud speech engine receives its hints, so clipboard text may
/// become one only when the speech engine runs on this Mac (`StreamingASREngine.speechHintsLeaveThisMac` is false). Even then,
/// contents that a password manager or a similar app marked as private are never used.
enum SpeechHintPrivacy {
    /// Pasteboard types that mark clipboard contents as private or short-lived. These are the nspasteboard.org markers plus
    /// legacy markers used by password managers and clipboard tools.
    static let privateClipboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb"
    ]

    /// True when `pasteboard` carries one of `privateClipboardTypes`, on the pasteboard itself or on any of its items. Both are
    /// checked because neither is complete: a marker that is not a valid UTI ("Pasteboard generator type") appears only in the
    /// pasteboard's own list, and that list is not documented to cover every item.
    static func isMarkedPrivate(_ pasteboard: NSPasteboard) -> Bool {
        let marked = privateClipboardTypes
        if (pasteboard.types ?? []).contains(where: { marked.contains($0.rawValue) }) {
            return true
        }
        return (pasteboard.pasteboardItems ?? []).contains { item in
            item.types.contains(where: { marked.contains($0.rawValue) })
        }
    }

    /// The clipboard text to use as a speech hint, or "" when it must not be used.
    /// - When the hints would leave this Mac, "" at once: the pasteboard is not touched.
    /// - When the contents are marked private, "".
    /// - Otherwise the trimmed text, if it is one line of 2 to 42 characters; anything else gives "".
    static func clipboardHintText(from pasteboard: NSPasteboard, speechHintsLeaveThisMac: Bool) -> String {
        guard !speechHintsLeaveThisMac else { return "" }
        guard !isMarkedPrivate(pasteboard) else { return "" }
        let text = (pasteboard.string(forType: .string) ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        return (text.count >= 2 && text.count <= 42 && !text.contains("\n")) ? text : ""
    }
}
